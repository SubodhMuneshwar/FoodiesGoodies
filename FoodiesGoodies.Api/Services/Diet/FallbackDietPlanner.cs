    private List<GroceryCategoryDto> BuildWeeklyGroceryList(List<DietDayDto> days, CuisineContextDto cuisine, string diet)
    {
        var produceSet = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var grainsSet = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var proteinSet = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var spicesSet = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        var otherSet = new HashSet<string>(StringComparer.OrdinalIgnoreCase);

        foreach (var day in days)
        {
            foreach (var meal in day.Meals)
            {
                foreach (var ing in meal.Ingredients)
                {
                    string item = ing.Trim();
                    string lower = item.ToLowerInvariant();

                    if (lower.Contains("spinach") || lower.Contains("palak") || lower.Contains("methi") ||
                        lower.Contains("tomato") || lower.Contains("onion") || lower.Contains("cucumber") ||
                        lower.Contains("carrot") || lower.Contains("lemon") || lower.Contains("cilantro") ||
                        lower.Contains("ginger") || lower.Contains("garlic") || lower.Contains("apple") ||
                        lower.Contains("berry") || lower.Contains("pomegranate") || lower.Contains("avocado") ||
                        lower.Contains("zucchini") || lower.Contains("bok choy") || lower.Contains("gourd") ||
                        lower.Contains("pumpkin") || lower.Contains("drumstick"))
                    {
                        produceSet.Add(item);
                    }
                    else if (lower.Contains("rice") || lower.Contains("poha") || lower.Contains("jowar") ||
                             lower.Contains("bajra") || lower.Contains("atta") || lower.Contains("wheat") ||
                             lower.Contains("oats") || lower.Contains("quinoa") || lower.Contains("bread") ||
                             lower.Contains("soba") || lower.Contains("farro") || lower.Contains("tortilla"))
                    {
                        grainsSet.Add(item);
                    }
                    else if (lower.Contains("paneer") || lower.Contains("tofu") || lower.Contains("salmon") ||
                             lower.Contains("chicken") || lower.Contains("egg") || lower.Contains("dal") ||
                             lower.Contains("moong") || lower.Contains("chana") || lower.Contains("matki") ||
                             lower.Contains("rajma") || lower.Contains("lentil") || lower.Contains("edamame") ||
                             lower.Contains("curd") || lower.Contains("dahi") || lower.Contains("yogurt") ||
                             lower.Contains("feta") || lower.Contains("makhana"))
                    {
                        proteinSet.Add(item);
                    }
                    else if (lower.Contains("masala") || lower.Contains("cumin") || lower.Contains("mustard") ||
                             lower.Contains("turmeric") || lower.Contains("ghee") || lower.Contains("oil") ||
                             lower.Contains("kokum") || lower.Contains("pepper") || lower.Contains("salt") ||
                             lower.Contains("miso") || lower.Contains("oregano") || lower.Contains("tahini"))
                    {
                        spicesSet.Add(item);
                    }
                    else
                    {
                        otherSet.Add(item);
                    }
                }
            }
        }

        return new List<GroceryCategoryDto>
        {
            new GroceryCategoryDto { Category = "Fresh Produce & Herbs", Items = produceSet.Take(12).ToList() },
            new GroceryCategoryDto { Category = "Whole Grains & Staples", Items = grainsSet.Take(8).ToList() },
            new GroceryCategoryDto { Category = "Proteins, Legumes & Dairy", Items = proteinSet.Take(10).ToList() },
            new GroceryCategoryDto { Category = "Traditional Spices & Oils", Items = spicesSet.Take(8).ToList() },
            new GroceryCategoryDto { Category = "Pantry Essentials", Items = otherSet.Take(6).ToList() }
        };
    }
