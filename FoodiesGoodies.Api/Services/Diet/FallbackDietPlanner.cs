    public DietPlanResponse Generate7DayFallbackPlan(DietPlanRequest request, NutritionTargetsDto targets, CuisineContextDto cuisine)
    {
        ArgumentNullException.ThrowIfNull(request);
        ArgumentNullException.ThrowIfNull(targets);
        ArgumentNullException.ThrowIfNull(cuisine);

        int mealCount = Math.Clamp(request.MealCount, 3, 5);
        int targetCals = targets.TargetCalories > 0 ? targets.TargetCalories : 2000;
        string diet = (request.DietPreference ?? "omnivore").ToLowerInvariant();
        string cuisineName = (cuisine.Name ?? "Balanced").ToLowerInvariant();

        var days = new List<DietDayDto>();

        for (int dayNum = 1; dayNum <= 7; dayNum++)
        {
            var dayMeals = GenerateMealsForDay(dayNum, mealCount, targetCals, diet, cuisine, request);
            int dayCal = dayMeals.Sum(m => m.Calories);
            int dayProtein = dayMeals.Sum(m => m.ProteinGrams);
            int dayCarbs = dayMeals.Sum(m => m.CarbsGrams);
            int dayFat = dayMeals.Sum(m => m.FatGrams);

            days.Add(new DietDayDto
            {
                Day = dayNum,
                DayName = $"Day {dayNum}",
                Meals = dayMeals,
                TotalCalories = dayCal,
                TotalProteinGrams = dayProtein,
                TotalCarbsGrams = dayCarbs,
                TotalFatGrams = dayFat
            });
        }

        var groceryList = BuildWeeklyGroceryList(days, cuisine, diet);

        return new DietPlanResponse
        {
            PlanTitle = $"7-Day Personalized {cuisine.Name} Nutrition Plan",
            PlanSource = "FoodiesGoodies Planning Engine",
            Cuisine = cuisine,
            Nutrition = targets,
            Days = days,
            GroceryList = groceryList,
            Recommendations = new List<string>
            {
                $"Daily Calorie Target: ~{targets.TargetCalories} kcal calibrated for {targets.GoalLabel}.",
                $"Hydration: Maintain at least {targets.HydrationLiters} Liters ({targets.HydrationOz} fl oz) of clean water daily.",
                $"Cooking Wisdom: Max cooking time budgeted at {request.MaxCookingTimeMinutes} minutes using authentic {cuisine.Name} spices."
            },
            DigestiveTip = cuisine.DigestiveTradition ?? "Sip warm cumin-fennel infusion after main meals to assist digestion.",
            Disclaimer = "Gemini is temporarily unavailable. Showing a personalized plan generated by the FoodiesGoodies nutrition planning engine.",
            GeneratedAtUtc = DateTime.UtcNow
        };
    }

    public DietMealDto GenerateFallbackSwapMeal(MealSwapRequest request)
    {
        ArgumentNullException.ThrowIfNull(request);

        int cals = request.TargetCalories > 0 ? request.TargetCalories : 500;
        string category = request.MealCategory ?? "Dinner";
        string cuisine = request.Cuisine ?? "Maharashtrian";
        string diet = request.DietPreference ?? "vegetarian";

        return CreateAlternativeMeal(request.Day, category, cals, diet, cuisine, request.MaxCookingTimeMinutes);
    }

    private List<DietMealDto> GenerateMealsForDay(
        int dayNum,
        int mealCount,
        int totalCals,
        string diet,
        CuisineContextDto cuisine,
        DietPlanRequest request)
    {
        var meals = new List<DietMealDto>();
        bool isVeg = diet.Contains("veg");
        bool isVegan = diet.Contains("vegan");
        bool isKeto = diet.Contains("keto");
        string cuisineName = cuisine.Name.ToLowerInvariant();

        // Calorie splits
        int bfastCals, lunchCals, snackCals = 0, snack2Cals = 0, dinnerCals;

        if (mealCount == 3)
        {
            bfastCals = (int)Math.Round(totalCals * 0.28);
            lunchCals = (int)Math.Round(totalCals * 0.38);
            dinnerCals = totalCals - bfastCals - lunchCals;
        }
        else if (mealCount == 5)
        {
            bfastCals = (int)Math.Round(totalCals * 0.22);
            lunchCals = (int)Math.Round(totalCals * 0.30);
            snackCals = (int)Math.Round(totalCals * 0.12);
            snack2Cals = (int)Math.Round(totalCals * 0.10);
            dinnerCals = totalCals - bfastCals - lunchCals - snackCals - snack2Cals;
        }
        else // 4 meals default
        {
            bfastCals = (int)Math.Round(totalCals * 0.25);
            lunchCals = (int)Math.Round(totalCals * 0.35);
            snackCals = (int)Math.Round(totalCals * 0.15);
            dinnerCals = totalCals - bfastCals - lunchCals - snackCals;
        }

        // Breakfast
        meals.Add(CreateMeal(dayNum, "Breakfast", bfastCals, diet, cuisineName, 0, request.MaxCookingTimeMinutes));

        // Lunch
        meals.Add(CreateMeal(dayNum, "Lunch", lunchCals, diet, cuisineName, 1, request.MaxCookingTimeMinutes));

        // Afternoon Snack
        if (mealCount >= 4)
        {
            meals.Add(CreateMeal(dayNum, "Snack", snackCals, diet, cuisineName, 2, Math.Min(15, request.MaxCookingTimeMinutes)));
        }

        // Second Snack for 5-meal schedule
        if (mealCount == 5)
        {
            meals.Add(CreateMeal(dayNum, "Evening Fuel", snack2Cals, diet, cuisineName, 3, Math.Min(15, request.MaxCookingTimeMinutes)));
        }

        // Dinner
        meals.Add(CreateMeal(dayNum, "Dinner", dinnerCals, diet, cuisineName, 4, request.MaxCookingTimeMinutes));

        return meals;
    }

    private DietMealDto CreateMeal(int dayNum, string category, int cals, string diet, string cuisine, int slot, int maxCookingTime)
    {
        int p = (int)Math.Round(cals * 0.28 / 4);
        int c = (int)Math.Round(cals * 0.47 / 4);
        int f = (int)Math.Round(cals * 0.25 / 9);

        // Maharashtrian / North Indian / South Indian / Mediterranean / Japanese / Mexican specific templates
        if (cuisine.Contains("maharashtr"))
        {
            return GetMaharashtrianMeal(dayNum, category, cals, p, c, f, diet, maxCookingTime);
        }
        else if (cuisine.Contains("south indian"))
        {
            return GetSouthIndianMeal(dayNum, category, cals, p, c, f, diet, maxCookingTime);
        }
        else if (cuisine.Contains("north indian") || cuisine.Contains("punjab"))
        {
            return GetNorthIndianMeal(dayNum, category, cals, p, c, f, diet, maxCookingTime);
        }
        else if (cuisine.Contains("japan"))
        {
            return GetJapaneseMeal(dayNum, category, cals, p, c, f, diet, maxCookingTime);
        }
        else if (cuisine.Contains("mediterran") || cuisine.Contains("greek") || cuisine.Contains("ital"))
        {
            return GetMediterraneanMeal(dayNum, category, cals, p, c, f, diet, maxCookingTime);
        }
        else if (cuisine.Contains("mexic"))
        {
            return GetMexicanMeal(dayNum, category, cals, p, c, f, diet, maxCookingTime);
        }

        // Default Balanced
        return GetGlobalMeal(dayNum, category, cals, p, c, f, diet, maxCookingTime);
    }

